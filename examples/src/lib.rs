//! # nsk-examples
//!
//! Runnable usage examples for the NSK kernel. This crate has no library
//! code on purpose: each entry point lives in [`examples/`](../) and runs
//! with `cargo run -p nsk-examples --example <name>`.
//!
//! See [examples/README.md](../README.md) for the catalog (scenario, run
//! command, and the equivalent `nsk` CLI invocation per example).
